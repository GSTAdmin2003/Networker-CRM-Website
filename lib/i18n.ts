export function makeT(lang: Lang, cmsOverrides: Record<string, string> = {}) {
  return (key: string): string => {
    const cmsKey = `${key}_${lang}`
    if (cmsOverrides[cmsKey]) return cmsOverrides[cmsKey]
    return I18N[lang][key] ?? I18N['en'][key] ?? key
  }
}
